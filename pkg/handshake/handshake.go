// =============================================================================
// RTMP ハンドシェイク
// =============================================================================
//
// 【ハンドシェイクとは】
// RTMPの通信はTCP接続確立後、まずハンドシェイクから始まる。
// クライアントとサーバーが互いにバージョン情報とランダムデータを交換し、
// 通信の準備が整ったことを確認するための手順。
//
// 【ハンドシェイクの流れ】
//
//   クライアント                       サーバー
//       |                                |
//       |--- C0 (1バイト: バージョン) -->|
//       |--- C1 (1536バイト) ----------->|
//       |                                |
//       |<-- S0 (1バイト: バージョン) ---|
//       |<-- S1 (1536バイト) ------------|
//       |<-- S2 (1536バイト: C1のエコー)-|
//       |                                |
//       |--- C2 (1536バイト: S1のエコー)->|
//       |                                |
//       |    ★ ハンドシェイク完了 ★      |
//
// 【各パケットの構造】
//
// C0/S0 (1バイト):
//   - RTMPバージョン番号（通常は3）
//   - バージョン3はプレーンなRTMP（暗号化なし）を示す
//
// C1/S1 (1536バイト):
//   - タイムスタンプ (4バイト): 送信側の基準時刻
//   - ゼロ (4バイト): 未使用領域（将来の拡張用）
//   - ランダムデータ (1528バイト): 任意のバイト列
//
// C2/S2 (1536バイト):
//   - タイムスタンプ (4バイト): 相手のC1/S1から受け取ったタイムスタンプ
//   - タイムスタンプ2 (4バイト): C2/S2を送信する時点のタイムスタンプ
//   - ランダムデータエコー (1528バイト): 相手のC1/S1のランダムデータをそのまま返す
//
// 【なぜハンドシェイクが必要か】
// 1. プロトコルバージョンの合意
// 2. 帯域幅の初期推定（タイムスタンプの差分でRTTを推定）
// 3. 接続の正当性確認（ランダムデータのエコーバック）
//
package handshake

import (
	"crypto/rand"
	"encoding/binary"
	"fmt"
	"io"
	"time"
)

// RTMPプロトコルバージョン（バージョン3 = プレーンRTMP、暗号化なし）
const RTMPVersion = 3

// ハンドシェイクパケットのサイズ（C1/S1/C2/S2は全て1536バイト固定）
const HandshakeSize = 1536

// =============================================================================
// サーバー側ハンドシェイク
// =============================================================================

// ServerHandshake はサーバー側のハンドシェイク処理を行う。
//
// 手順:
//   1. クライアントからC0+C1を受信
//   2. S0+S1+S2をクライアントに送信
//   3. クライアントからC2を受信
//   4. C2の内容を検証（S1のエコーバックが正しいか）
func ServerHandshake(rw io.ReadWriter) error {
	// -----------------------------------------------------------------------
	// ステップ1: C0を読み取る（1バイト = RTMPバージョン番号）
	// -----------------------------------------------------------------------
	c0 := make([]byte, 1)
	if _, err := io.ReadFull(rw, c0); err != nil {
		return fmt.Errorf("ハンドシェイク: C0の読み取りに失敗: %w", err)
	}
	if c0[0] != RTMPVersion {
		return fmt.Errorf("ハンドシェイク: サポートされていないバージョン: %d (期待: %d)", c0[0], RTMPVersion)
	}

	// -----------------------------------------------------------------------
	// ステップ2: C1を読み取る（1536バイト）
	// -----------------------------------------------------------------------
	c1 := make([]byte, HandshakeSize)
	if _, err := io.ReadFull(rw, c1); err != nil {
		return fmt.Errorf("ハンドシェイク: C1の読み取りに失敗: %w", err)
	}

	// -----------------------------------------------------------------------
	// ステップ3: S0を送信（1バイト = RTMPバージョン番号）
	// -----------------------------------------------------------------------
	s0 := []byte{RTMPVersion}
	if _, err := rw.Write(s0); err != nil {
		return fmt.Errorf("ハンドシェイク: S0の送信に失敗: %w", err)
	}

	// -----------------------------------------------------------------------
	// ステップ4: S1を生成して送信（1536バイト）
	// -----------------------------------------------------------------------
	s1 := make([]byte, HandshakeSize)
	// 先頭4バイト: タイムスタンプ（サーバーの基準時刻）
	timestamp := uint32(time.Now().UnixMilli())
	binary.BigEndian.PutUint32(s1[0:4], timestamp)
	// 次の4バイト: ゼロ（未使用領域）
	binary.BigEndian.PutUint32(s1[4:8], 0)
	// 残り1528バイト: ランダムデータ
	if _, err := rand.Read(s1[8:]); err != nil {
		return fmt.Errorf("ハンドシェイク: ランダムデータの生成に失敗: %w", err)
	}
	if _, err := rw.Write(s1); err != nil {
		return fmt.Errorf("ハンドシェイク: S1の送信に失敗: %w", err)
	}

	// -----------------------------------------------------------------------
	// ステップ5: S2を生成して送信（C1のエコーバック）
	// -----------------------------------------------------------------------
	// S2はC1の内容をほぼそのまま返す（タイムスタンプ2だけ更新）
	s2 := make([]byte, HandshakeSize)
	copy(s2, c1)
	// 4-7バイト目をS2送信時のタイムスタンプで上書き
	binary.BigEndian.PutUint32(s2[4:8], uint32(time.Now().UnixMilli()))
	if _, err := rw.Write(s2); err != nil {
		return fmt.Errorf("ハンドシェイク: S2の送信に失敗: %w", err)
	}

	// -----------------------------------------------------------------------
	// ステップ6: C2を読み取る（1536バイト = S1のエコーバック）
	// -----------------------------------------------------------------------
	c2 := make([]byte, HandshakeSize)
	if _, err := io.ReadFull(rw, c2); err != nil {
		return fmt.Errorf("ハンドシェイク: C2の読み取りに失敗: %w", err)
	}

	// C2のランダムデータ部分がS1と一致するか確認
	// （簡易検証: 厳密な検証は省略。多くの実装でも省略されている）

	return nil
}

// =============================================================================
// クライアント側ハンドシェイク
// =============================================================================

// ClientHandshake はクライアント側のハンドシェイク処理を行う。
//
// 手順:
//   1. C0+C1をサーバーに送信
//   2. サーバーからS0+S1+S2を受信
//   3. C2をサーバーに送信（S1のエコーバック）
func ClientHandshake(rw io.ReadWriter) error {
	// -----------------------------------------------------------------------
	// ステップ1: C0を送信（RTMPバージョン番号）
	// -----------------------------------------------------------------------
	c0 := []byte{RTMPVersion}
	if _, err := rw.Write(c0); err != nil {
		return fmt.Errorf("ハンドシェイク: C0の送信に失敗: %w", err)
	}

	// -----------------------------------------------------------------------
	// ステップ2: C1を生成して送信（1536バイト）
	// -----------------------------------------------------------------------
	c1 := make([]byte, HandshakeSize)
	// 先頭4バイト: タイムスタンプ
	timestamp := uint32(time.Now().UnixMilli())
	binary.BigEndian.PutUint32(c1[0:4], timestamp)
	// 次の4バイト: ゼロ
	binary.BigEndian.PutUint32(c1[4:8], 0)
	// 残り: ランダムデータ
	if _, err := rand.Read(c1[8:]); err != nil {
		return fmt.Errorf("ハンドシェイク: ランダムデータの生成に失敗: %w", err)
	}
	if _, err := rw.Write(c1); err != nil {
		return fmt.Errorf("ハンドシェイク: C1の送信に失敗: %w", err)
	}

	// -----------------------------------------------------------------------
	// ステップ3: S0を受信（1バイト）
	// -----------------------------------------------------------------------
	s0 := make([]byte, 1)
	if _, err := io.ReadFull(rw, s0); err != nil {
		return fmt.Errorf("ハンドシェイク: S0の読み取りに失敗: %w", err)
	}
	if s0[0] != RTMPVersion {
		return fmt.Errorf("ハンドシェイク: サポートされていないバージョン: %d", s0[0])
	}

	// -----------------------------------------------------------------------
	// ステップ4: S1を受信（1536バイト）
	// -----------------------------------------------------------------------
	s1 := make([]byte, HandshakeSize)
	if _, err := io.ReadFull(rw, s1); err != nil {
		return fmt.Errorf("ハンドシェイク: S1の読み取りに失敗: %w", err)
	}

	// -----------------------------------------------------------------------
	// ステップ5: S2を受信（1536バイト）
	// -----------------------------------------------------------------------
	s2 := make([]byte, HandshakeSize)
	if _, err := io.ReadFull(rw, s2); err != nil {
		return fmt.Errorf("ハンドシェイク: S2の読み取りに失敗: %w", err)
	}
	_ = s2 // S2はC1のエコーバック（検証は省略）

	// -----------------------------------------------------------------------
	// ステップ6: C2を生成して送信（S1のエコーバック）
	// -----------------------------------------------------------------------
	c2 := make([]byte, HandshakeSize)
	copy(c2, s1)
	binary.BigEndian.PutUint32(c2[4:8], uint32(time.Now().UnixMilli()))
	if _, err := rw.Write(c2); err != nil {
		return fmt.Errorf("ハンドシェイク: C2の送信に失敗: %w", err)
	}

	return nil
}
